"""Tables generated from the CSV results in ../experiments/results; runs nothing itself.

    python tables.py   ->  rewrites the marked table blocks inside main.tex

Currently: Table "Injected errors" (tab:synthetic) from synthetic.csv. In each category the best F1
(after rounding to two decimals) is set in bold; ties are all bold.
"""

import csv
import re
from decimal import ROUND_HALF_UP, Decimal
from pathlib import Path

HERE = Path(__file__).resolve().parent
RES = HERE.parent / "experiments" / "results"
BEGIN = "% --- table synthetic (generated by tables.py) ---"
END = "% --- end table synthetic ---"

CATEGORIES = [("15", "CPV 15"), ("03", "CPV 03")]
METHODS = [
    ("3σ, клас ДК 021", r"3$\sigma$, CPV class"),
    ("Isolation Forest у групах (бюджет v2)", "Isolation Forest in groups"),
    ("v1", "v1"),
    ("перший етап v2", "v2 screening"),
    ("v2, калібратор на першій розмітці (з рішеннями v1)", "v2, calibrator on sighted labels"),
    ("v2, калібратор на сліпій розмітці, монотонний", "v2, monotone calibrator on blind labels"),
    ("гібрид, калібратор на сліпій розмітці, монотонний", "hybrid, same calibrator"),
]
RECALLS = ["recall moderate", "recall strong", "recall unit", "recall lot_total"]


def rnd(x: str, places: int) -> str:
    """Round the decimal string half-up (0.175 -> 0.18), without binary floating-point artefacts."""
    return str(Decimal(x).quantize(Decimal(1).scaleb(-places), rounding=ROUND_HALF_UP))


def f2(x: str) -> str:
    return rnd(x, 2)


def table() -> str:
    with open(RES / "synthetic.csv", encoding="utf-8-sig", newline="") as fh:
        rows = list(csv.DictReader(fh))
    lines = [
        r"\begin{tabular}{llccccccc}",
        r"\toprule",
        r" & Method & F1 & AP & Flagged & R mod. & R strong & R unit & R lot \\",
    ]
    for code, name in CATEGORIES:
        sub = {r["метод"]: r for r in rows if r["категорія"].startswith(code)}
        missing = [m for m, _ in METHODS if m not in sub]
        if missing:
            raise SystemExit(f"synthetic.csv, CPV {code}: missing {missing}")
        best = max(f2(sub[m]["f1"]) for m, _ in METHODS)
        lines.append(r"\midrule")
        for k, (m, label) in enumerate(METHODS):
            r = sub[m]
            f1 = f2(r["f1"])
            cells = [
                rf"\textbf{{{f1}}}" if f1 == best else f1,
                f2(r["ap"]),
                rnd(r["позначено, %"], 1) + r"\%",
                *(f2(r[c]) for c in RECALLS),
            ]
            if k == 0:
                lines.append(rf"\multirow{{{len(METHODS)}}}{{*}}{{{name}}}")
            lines.append(f" & {label} & " + " & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines)


def main() -> None:
    path = HERE / "main.tex"
    tex = path.read_text(encoding="utf8")
    if BEGIN not in tex:
        raise SystemExit(f"marker not found in main.tex: {BEGIN}")
    block = f"{BEGIN}\n{table()}\n{END}"
    tex = re.sub(re.escape(BEGIN) + ".*?" + re.escape(END), lambda _: block, tex, flags=re.S)
    path.write_text(tex, encoding="utf8")
    print("tab:synthetic written")


if __name__ == "__main__":
    main()
