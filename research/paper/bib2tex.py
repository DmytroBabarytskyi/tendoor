"""refs.bib -> thebibliography inside main.tex (arXiv compiles without BibTeX).

Only cited entries are kept, in order of first citation. Re-run after editing refs.bib:
    python bib2tex.py
"""

import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
BEGIN, END = "% --- bibliography (generated by bib2tex.py) ---", "% --- end bibliography ---"


def parse(text: str) -> dict[str, dict]:
    out = {}
    for m in re.finditer(r"@(\w+)\s*\{\s*([^,]+),(.*?)\n\}", text, re.S):
        kind, key, body = m.group(1).lower(), m.group(2).strip(), m.group(3)
        fields = {}
        for f in re.finditer(r"(\w+)\s*=\s*\{((?:[^{}]|\{(?:[^{}]|\{[^{}]*\})*\})*)\}", body):
            fields[f.group(1).lower()] = " ".join(f.group(2).split())
        fields["_type"] = kind
        out[key] = fields
    return out


def initial(name: str) -> str:
    """Ініціали імені; подвійні імена через дефіс зберігають дефіс: Hans-Peter -> H.-P."""
    return "-".join(part[0] + "." for part in name.split("-") if part)


def authors(s: str) -> str:
    names = [a.strip() for a in s.split(" and ")]
    fmt = []
    for n in names:
        if n == "others":
            fmt.append("et al.")
            continue
        if "," in n:
            last, first = [p.strip() for p in n.split(",", 1)]
            initials = " ".join(initial(p) for p in re.split(r"[\s~]+", first) if p and p[0].isalpha())
            fmt.append(f"{initials} {last}".strip())
        else:
            fmt.append(n)
    if len(fmt) > 6:  # IEEE: понад шість авторів — перший і et al.
        fmt = fmt[:1] + ["et al."]
    if fmt and fmt[-1] == "et al.":
        return ", ".join(fmt[:-1]) + " et al."
    if len(fmt) <= 2:
        return " and ".join(fmt)
    return ", ".join(fmt[:-1]) + ", and " + fmt[-1]


def entry(f: dict) -> str:
    """Запис у стилі IEEE."""
    a = authors(f.get("author", ""))
    t, y = f.get("title", ""), f.get("year", "")
    doi = f" \\doi{{{f['doi']}}}" if "doi" in f else ""
    kind = f["_type"]
    if kind == "article":
        vol = f", vol.~{f['volume']}" if "volume" in f else ""
        num = f", no.~{f['number']}" if "number" in f else ""
        pages = f.get('pages', '')
        pg = (f", pp.~{pages}" if "--" in pages else f", Art.~no.~{pages}") if pages else ""
        return f"{a}, ``{t},'' \\emph{{{f.get('journal', '')}}}{vol}{num}{pg}, {y}.{doi}"
    if kind in ("inproceedings", "incollection"):
        vol = f", vol.~{f['volume']}" if "volume" in f and "series" not in f else ""
        pages = f", pp.~{f['pages']}" if "pages" in f else ""
        return f"{a}, ``{t},'' in \\emph{{{f.get('booktitle', '')}}}{vol}{pages}, {y}.{doi}"
    if kind == "book":
        return f"{a}, \\emph{{{t}}}. {f.get('address', '')}: {f.get('publisher', '')}, {y}."
    # misc / web
    year = f" {y}." if y else ""
    note = f". {f['note']}." if "note" in f else "."
    return f"{a}, ``{t},''{year} [Online]. Available: {f.get('howpublished', '')}{note}"


def main() -> None:
    tex_path = HERE / "main.tex"
    tex = tex_path.read_text(encoding="utf8")
    bib = parse((HERE / "refs.bib").read_text(encoding="utf8"))
    body = tex.split(BEGIN)[0]
    order = []
    for group in re.findall(r"\\cite[pt]?\{([^}]+)\}", body):
        for k in group.split(","):
            k = k.strip()
            if k not in order:
                order.append(k)
    missing = [k for k in order if k not in bib]
    if missing:
        raise SystemExit(f"missing in refs.bib: {missing}")
    items = "\n".join(f"\\bibitem{{{k}}}\n{entry(bib[k])}\n" for k in order)
    block = f"{BEGIN}\n\\begin{{thebibliography}}{{{len(order)}}}\n\n{items}\n\\end{{thebibliography}}\n{END}"
    if BEGIN in tex:
        tex = re.sub(re.escape(BEGIN) + ".*?" + re.escape(END), lambda _: block, tex, flags=re.S)
    else:
        tex = re.sub(r"\\bibliographystyle\{[^}]*\}\s*\\bibliography\{[^}]*\}", lambda _: block, tex)
    tex_path.write_text(tex, encoding="utf8")
    print(f"{len(order)} references written")


if __name__ == "__main__":
    main()
